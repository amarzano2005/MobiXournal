package com.mobixournal.render

import com.mobixournal.format.model.Stroke
import com.mobixournal.format.model.StrokePoint
import com.mobixournal.format.model.Tool
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import kotlin.math.hypot

/**
 * The resize of a **headed figure**: read the vertices back into parameters, then re-emit the figure
 * at the new anchors and the head size it was drawn with.
 *
 * This is the rule `docs/stylus.md` states — *a figure is resized, not thickened* — and the point of
 * re-emitting rather than stretching is that none of it is approximate: the head is the number the
 * tool chose, the vertices are generated by the same builder the tool used, and a resize by 1.0 has to
 * give the stroke back exactly as it went in. Each of those is pinned below, because each was a way
 * the previous "stretch, then pin the barbs" implementation could fail.
 */
class FigureRedrawTest {

    private fun stroke(points: List<StrokePoint>) = Stroke(
        tool = Tool.PEN,
        color = 0xFF000000.toInt(),
        capStyle = null,
        points = points,
        uniformWidth = true,
    )

    private fun resize(
        points: List<StrokePoint>,
        sx: Double,
        sy: Double,
        dx: Double = 0.0,
        dy: Double = 0.0,
    ): List<StrokePoint> =
        (SelectionOps.affineXY(stroke(points), sx, sy, dx, dy, scaleWidth = false) as Stroke).points

    private fun distance(a: StrokePoint, b: StrokePoint) = hypot(a.x - b.x, a.y - b.y)

    private fun arrow(sx: Double, sy: Double, ex: Double, ey: Double, w: Double = 2.0) =
        ShapeBuilder.build(ShapeKind.ARROW, sx, sy, ex, ey, w)

    /** The head a pen of [w] wears on a 100 pt shaft — the rule `FigureGeometry` states. */
    private fun drawnHead(w: Double) = FigureGeometry.headPt(w, 100.0)

    @Test
    fun `an arrow is recognised from its five vertices`() {
        assertNotNull(FigureRedraw.read(arrow(0.0, 0.0, 100.0, 0.0)))
    }

    @Test
    fun `a plain stroke is not a figure`() {
        val squiggle = listOf(
            StrokePoint(0.0, 0.0, 1.0),
            StrokePoint(10.0, 4.0, 1.0),
            StrokePoint(20.0, 0.0, 1.0),
        )
        assertNull(FigureRedraw.read(squiggle))
        // …and it still resizes point for point.
        val scaled = resize(squiggle, 2.0, 3.0, dx = 5.0, dy = -5.0)
        assertEquals(5.0, scaled[0].x, 1e-12)
        assertEquals(-5.0, scaled[0].y, 1e-12)
        assertEquals(25.0, scaled[1].x, 1e-12)
        assertEquals(45.0, scaled[2].x, 1e-12)
        assertEquals("a resize widens the figure, not its line", 1.0, scaled[2].width, 1e-12)
    }

    @Test
    fun `resizing by one gives the very same arrow back`() {
        // The strongest statement that the redraw is the tool's own geometry and not an approximation:
        // read + re-emit at 1× is the identity, so a drag that returns to where it started returns to
        // exactly the figure it started with — no drift for repeated resizes to accumulate.
        val original = arrow(20.0, 30.0, 120.0, 130.0)
        val same = resize(original, 1.0, 1.0)

        assertEquals(original.size, same.size)
        original.indices.forEach { i ->
            assertEquals("vertex $i x", original[i].x, same[i].x, 1e-9)
            assertEquals("vertex $i y", original[i].y, same[i].y, 1e-9)
        }
    }

    @Test
    fun `doubling the arrow doubles the shaft and leaves the head alone`() {
        val original = arrow(10.0, 50.0, 110.0, 50.0)
        val head = distance(original[1], original[2])
        assertEquals("the head is the pen's own 6 × width", drawnHead(2.0), head, 1e-9)

        val doubled = resize(original, 2.0, 2.0)

        // Tail and tip travel; the barbs stay the size they were drawn.
        assertEquals(20.0, doubled[0].x, 1e-9)
        assertEquals(220.0, doubled[1].x, 1e-9)
        assertEquals(head, distance(doubled[1], doubled[2]), 1e-9)
        assertEquals(head, distance(doubled[1], doubled[4]), 1e-9)
        // Still a V about the stretched shaft, i.e. the two barbs are mirror images of each other.
        assertEquals(doubled[2].y - doubled[1].y, -(doubled[4].y - doubled[1].y), 1e-9)
    }

    @Test
    fun `a one-axis stretch keeps the head its drawn size instead of flattening it`() {
        val original = arrow(0.0, 0.0, 100.0, 0.0)
        val head = distance(original[1], original[2])

        val stretched = resize(original, 3.0, 1.0)

        assertEquals(300.0, stretched[1].x, 1e-9)
        assertEquals(head, distance(stretched[1], stretched[2]), 1e-9)
        assertEquals(head, distance(stretched[1], stretched[4]), 1e-9)
        // The V's opening is still the tool's own: the barbs turned with the shaft, not squashed.
        val angle = Math.toDegrees(
            kotlin.math.acos(
                ((stretched[2].x - stretched[1].x) * (stretched[4].x - stretched[1].x) +
                    (stretched[2].y - stretched[1].y) * (stretched[4].y - stretched[1].y)) /
                    (distance(stretched[1], stretched[2]) * distance(stretched[1], stretched[4])),
            ),
        )
        assertEquals(2 * FigureGeometry.HALF_ANGLE_DEG, angle, 0.001)
    }

    @Test
    fun `a shrunken arrow keeps a head that still reads as a head`() {
        // Shrinking to a fifth would keep an 18 pt head on a 20 pt shaft — a V the size of the figure.
        // The head is clamped to a share of the shaft instead, so the result is still an arrow.
        val original = arrow(0.0, 0.0, 100.0, 0.0)
        val shrunk = resize(original, 0.2, 0.2)

        val shaft = distance(shrunk[0], shrunk[1])
        val head = distance(shrunk[1], shrunk[2])
        assertTrue("the head must not swallow the shaft", head <= 0.6 * shaft + 1e-9)
        assertTrue("…but it is still a head", head > 0.0)
    }

    @Test
    fun `a double arrow keeps both heads`() {
        val original = ShapeBuilder.build(ShapeKind.DOUBLE_ARROW, 0.0, 0.0, 100.0, 0.0, 1.0)
        val head = distance(original[1], original[0])

        val stretched = resize(original, 1.5, 1.5)

        assertEquals(original.size, stretched.size)
        assertEquals(head, distance(stretched[1], stretched[0]), 1e-9)
        assertEquals(head, distance(stretched[1], stretched[2]), 1e-9)
        assertEquals(head, distance(stretched[4], stretched[5]), 1e-9)
        assertEquals(head, distance(stretched[4], stretched[7]), 1e-9)
    }

    @Test
    fun `the coordinate diagram keeps both heads and moves its origin`() {
        val original = ShapeBuilder.build(ShapeKind.COORDINATE_AXIS, 100.0, 100.0, 200.0, 60.0, 2.0)
        val xHead = distance(original[5], original[6])
        val yHead = distance(original[1], original[0])

        val doubled = resize(original, 2.0, 2.0)

        // The origin is a vertex of the figure, so it moves with the drag...
        assertEquals(200.0, doubled[4].x, 1e-9)
        assertEquals(200.0, doubled[4].y, 1e-9)
        // ...the tips travel to twice their distance...
        assertEquals(400.0, doubled[5].x, 1e-9)
        assertEquals(120.0, doubled[1].y, 1e-9)
        // ...and both heads are exactly the size they were drawn.
        assertEquals(xHead, distance(doubled[5], doubled[6]), 1e-9)
        assertEquals(xHead, distance(doubled[5], doubled[8]), 1e-9)
        assertEquals(yHead, distance(doubled[1], doubled[0]), 1e-9)
        assertEquals(yHead, distance(doubled[1], doubled[2]), 1e-9)
    }

    @Test
    fun `a head whose barbs were nudged apart is still recognised`() {
        // The endpoint snap moves a stroke's last vertex, which on an arrow is a barb. A head a few
        // percent off symmetry is still that arrow's head, and must not start growing with the shaft.
        val built = arrow(0.0, 0.0, 100.0, 0.0)
        val tip = built[1]
        val nudged = built.toMutableList()
        val last = nudged[nudged.lastIndex]
        nudged[nudged.lastIndex] = last.copy(
            x = tip.x + (last.x - tip.x) * 1.06,
            y = tip.y + (last.y - tip.y) * 1.06,
        )

        assertNotNull(FigureRedraw.read(nudged))

        val stretched = resize(nudged, 2.0, 2.0)
        // The redraw re-emits the head from the length it read, so the asymmetry the snap left is
        // straightened out rather than carried forward — both barbs come back the drawn size.
        assertEquals(drawnHead(2.0), distance(stretched[1], stretched[2]), 1e-9)
        assertEquals(drawnHead(2.0), distance(stretched[1], stretched[4]), 1e-9)
    }

    @Test
    fun `the figure's width is carried through untouched`() {
        val original = arrow(0.0, 0.0, 100.0, 0.0, w = 3.5)
        val doubled = resize(original, 2.0, 2.0)

        assertTrue(doubled.all { it.width == 3.5 })
    }

    @Test
    fun `a stroke with per-vertex widths is resized point for point instead`() {
        // A hand-drawn arrow can look like one of these figures; widening its vertices as a side
        // effect would throw away the pressure it was drawn with.
        val pen = listOf(
            StrokePoint(0.0, 0.0, 1.0),
            StrokePoint(100.0, 0.0, 2.0),
            StrokePoint(85.0, 9.0, 3.0),
            StrokePoint(100.0, 0.0, 2.0),
            StrokePoint(85.0, -9.0, 1.5),
        )
        assertNull(FigureRedraw.read(pen))

        val scaled = resize(pen, 2.0, 2.0)
        assertEquals(200.0, scaled[1].x, 1e-9)
        assertEquals(2.0, scaled[1].width, 1e-9)
    }
}
